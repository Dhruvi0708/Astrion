"""Storage abstraction for document files.

Keys are generated by the server (see ``build_storage_key``) and validated against a strict pattern
before any backend touches them, so no user-controlled string ever becomes part of a path or object key.
"""

import re
import uuid
from collections.abc import Iterator
from dataclasses import dataclass
from typing import BinaryIO, Protocol

# ws/<workspace uuid hex>/doc/<document uuid hex>/<sha256[:16]><.ext>
# Compact on purpose: deep storage roots on Windows must stay under the 260-character path limit.
_KEY_RE = re.compile(r"^ws/[0-9a-f]{32}/doc/[0-9a-f]{32}/[0-9a-f]{16}(\.[a-z0-9]{1,8})?$")


class StorageError(Exception):
    pass


class InvalidStorageKeyError(StorageError):
    pass


class ObjectNotFoundError(StorageError):
    pass


def validate_key(key: str) -> str:
    if not _KEY_RE.fullmatch(key):
        raise InvalidStorageKeyError("Invalid storage key.")
    return key


def build_storage_key(workspace_id: uuid.UUID, document_id: uuid.UUID, sha256: str, extension: str) -> str:
    """Stable, content-addressed key. Never includes the uploaded filename.

    The source isn't part of the key: a document's source is recorded in PostgreSQL, and keeping the
    key short keeps local paths portable.
    """
    ext = extension.lower() if re.fullmatch(r"\.[a-z0-9]{1,8}", extension.lower()) else ""
    return validate_key(f"ws/{workspace_id.hex}/doc/{document_id.hex}/{sha256[:16]}{ext}")


@dataclass(frozen=True)
class StoredObject:
    key: str
    size: int
    content_type: str


class StorageBackend(Protocol):
    name: str

    def put(self, key: str, data: BinaryIO, *, size: int, content_type: str) -> StoredObject: ...

    def open(self, key: str) -> Iterator[bytes]: ...

    def exists(self, key: str) -> bool: ...

    def delete(self, key: str) -> None: ...
